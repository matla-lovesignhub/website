    /* =========================
       LOVESIGN HUB DYNAMIC MENU SWITCH
       Words fit = show centred word menu
       Words do not fit = show left-aligned hamburger
    ========================= */

    (function() {
        function onReady(callback) {
            if (document.readyState === "loading") {
                document.addEventListener("DOMContentLoaded", callback);
            } else {
                callback();
            }
        }

        onReady(function() {
            var menus = document.querySelectorAll(".lsh-main-menu");

            if (!menus.length) {
                return;
            }

            function getNeededMenuWidth(menu, desktopMenu) {
                var clone = desktopMenu.cloneNode(true);

                /*
                  Important:
                  Remove Divi's normal desktop-menu class from the measuring copy,
                  so it does not get hidden by hamburger/overflow CSS while we measure it.
                */
                clone.classList.remove("et_pb_menu__menu");
                clone.classList.add("lsh-menu-measure-clone");
                clone.removeAttribute("id");

                var subMenus = clone.querySelectorAll(".sub-menu");
                subMenus.forEach(function(subMenu) {
                    subMenu.style.display = "none";
                });

                menu.appendChild(clone);

                var list = clone.querySelector("nav > ul") || clone.querySelector("ul");
                var width = 0;

                if (list) {
                    width = Math.ceil(list.scrollWidth || list.getBoundingClientRect().width);
                } else {
                    width = Math.ceil(clone.scrollWidth || clone.getBoundingClientRect().width);
                }

                clone.remove();

                return width;
            }

            function checkMenu(menu) {
                var wrap = menu.querySelector(".et_pb_menu__wrap") || menu;
                var desktopMenu = menu.querySelector(".et_pb_menu__menu");

                if (!wrap || !desktopMenu) {
                    return;
                }

                var availableWidth = Math.floor(wrap.getBoundingClientRect().width);
                var neededWidth = getNeededMenuWidth(menu, desktopMenu);

                /*
                  Safety buffer:
                  Switch to hamburger slightly before the menu words touch the edge.
                */
                var buffer = 24;

                if (neededWidth + buffer > availableWidth) {
                    menu.classList.add("lsh-menu-overflow");
                } else {
                    menu.classList.remove("lsh-menu-overflow");
                }
            }

            var scheduled = false;

            function checkAllMenus() {
                if (scheduled) {
                    return;
                }

                scheduled = true;

                window.requestAnimationFrame(function() {
                    menus.forEach(checkMenu);
                    scheduled = false;
                });
            }

            checkAllMenus();

            window.addEventListener("resize", checkAllMenus, {
                passive: true
            });
            window.addEventListener("orientationchange", checkAllMenus);

            if ("ResizeObserver" in window) {
                var observer = new ResizeObserver(checkAllMenus);

                menus.forEach(function(menu) {
                    observer.observe(menu);

                    var wrap = menu.querySelector(".et_pb_menu__wrap");
                    if (wrap) {
                        observer.observe(wrap);
                    }
                });
            }

            /*
              Extra checks for late-loading fonts and Divi layout changes.
            */
            setTimeout(checkAllMenus, 300);
            setTimeout(checkAllMenus, 1000);
            setTimeout(checkAllMenus, 2500);
